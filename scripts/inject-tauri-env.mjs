import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const envPath = path.join(root, ".env.tauri");
const outDir = path.join(root, "src", "generated");
const outPath = path.join(outDir, "tauriEnv.ts");

if (!fs.existsSync(envPath)) {
  console.error("Missing .env.tauri");
  process.exit(1);
}

fs.mkdirSync(outDir, { recursive: true });

const env = Object.fromEntries(
  fs
    .readFileSync(envPath, "utf8")
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith("#"))
    .map((line) => {
      const idx = line.indexOf("=");
      return [line.slice(0, idx), line.slice(idx + 1)];
    }),
);

const api = env.VITE_API_BASE_URL;
const minio = env.VITE_MINIO_BASE ?? "http://localhost:9000";

if (!api) {
  console.error(".env.tauri must define VITE_API_BASE_URL");
  process.exit(1);
}

const stamp = new Date().toISOString();

const source = `/** Generated by scripts/inject-tauri-env.mjs */
export const API_BASE_URL = ${JSON.stringify(api)};
export const MINIO_BASE = ${JSON.stringify(minio)};
export const BUILD_STAMP = ${JSON.stringify(stamp)};
`;

fs.writeFileSync(outPath, source, "utf8");
console.log(`Injected Tauri API: ${api}`);
console.log(`Build stamp: ${stamp}`);
